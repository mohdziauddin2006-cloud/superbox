#!/usr/bin/env node
/*
 * build-assets.mjs - stage, obfuscate and encrypt the Android web bundle.
 *
 * Usage:
 *   node tools/build-assets.mjs <assets-dir> <staging-dir> <BuildSecrets.java>
 *
 * The staged tree is what aapt2 packages. Every .js file is AES-256-GCM
 * encrypted at rest and only decrypted inside LocalServer for the WebView.
 * First-party scripts are additionally run through javascript-obfuscator.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execSync, execFileSync } from 'node:child_process';

const [assetsDir, outDir, secretsPath] = process.argv.slice(2);
if (!assetsDir || !outDir || !secretsPath) {
  console.error('usage: node tools/build-assets.mjs <assets> <out> <BuildSecrets.java>');
  process.exit(2);
}

const OBFUSCATE = new Set(['app.js', 'library.js', 'sources.js', 'libraries.js']);
const KEY = crypto.randomBytes(32);
const KEY_HEX = KEY.toString('hex');
const MAGIC = Buffer.from('SBX1');

function walk(dir, base = dir, list = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, base, list);
    else list.push(path.relative(base, full));
  }
  return list;
}

function encrypt(buffer) {
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', KEY, iv);
  const body = Buffer.concat([cipher.update(buffer), cipher.final()]);
  return Buffer.concat([MAGIC, iv, body, cipher.getAuthTag()]);
}

import { fileURLToPath } from 'node:url';

const localCli = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  'obfuscator/node_modules/javascript-obfuscator/bin/javascript-obfuscator'
);

function obfuscate(input, output) {
  const args = [
    input,
    '--output', output,
    '--compact', 'true',
    '--control-flow-flattening', 'true',
    '--control-flow-flattening-threshold', '0.45',
    '--dead-code-injection', 'true',
    '--dead-code-injection-threshold', '0.15',
    '--identifier-names-generator', 'hexadecimal',
    '--numbers-to-expressions', 'true',
    '--rename-globals', 'false',
    '--self-defending', 'false',
    '--simplify', 'true',
    '--string-array', 'true',
    '--string-array-encoding', 'base64',
    '--string-array-threshold', '0.75',
    '--string-array-rotate', 'true',
    '--string-array-shuffle', 'true',
    '--string-array-wrappers-count', '2',
    '--split-strings', 'true',
    '--split-strings-chunk-length', '8',
    '--transform-object-keys', 'true',
    '--disable-console-output', 'true',
    '--target', 'browser'
  ];
  if (fs.existsSync(localCli)) {
    execFileSync(process.execPath, [localCli, ...args], { stdio: 'inherit' });
    return;
  }
  const npx = process.platform === 'win32' ? 'npx.cmd' : 'npx';
  const cmd = [npx, '--yes', 'javascript-obfuscator@5.10.0', ...args].map(function (a) {
    return '"' + String(a).replace(/"/g, '\\"') + '"';
  }).join(' ');
  execSync(cmd, { stdio: 'inherit', shell: true });
}

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });

const files = walk(assetsDir);
for (const rel of files) {
  const src = path.join(assetsDir, rel);
  const dst = path.join(outDir, rel);
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  const name = path.basename(rel);
  if (rel.endsWith('.js')) {
    let payload;
    if (OBFUSCATE.has(name)) {
      const tmp = dst + '.obf.js';
      obfuscate(src, tmp);
      payload = fs.readFileSync(tmp);
      fs.rmSync(tmp, { force: true });
    } else {
      payload = fs.readFileSync(src);
    }
    fs.writeFileSync(dst + '.enc', encrypt(payload));
    console.log('encrypted', rel, '->', path.basename(dst) + '.enc', payload.length + ' bytes');
  } else {
    fs.copyFileSync(src, dst);
    console.log('copied    ', rel);
  }
}

const java = `package com.superbox.mobile;

/** Build-time secrets. Regenerated by tools/build-assets.mjs on every release build. */
final class BuildSecrets {
    private BuildSecrets() {}
    static final String AES_KEY_HEX = "${KEY_HEX}";
}
`;
fs.mkdirSync(path.dirname(secretsPath), { recursive: true });
fs.writeFileSync(secretsPath, java, 'utf8');
console.log('wrote', secretsPath);
console.log('staged', files.length, 'assets into', outDir);
